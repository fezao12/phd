import pandas as pd
import re

# --- 1. Exceções para match exato ---
exact_match_words = {"tin", "lead"}

# --- 2. Função de extração robusta (usa set para não duplicar) ---
def extract_keywords(text, keywords, exact_match_words):
    if pd.isna(text):
        return set()
    text = text.lower()
    found = set()
    for kw in keywords:
        kw_lc = kw.lower().strip()
        if kw_lc in exact_match_words:
            if re.search(rf'\b{re.escape(kw_lc)}\b', text):
                found.add(kw)
        else:
            if kw_lc in text:
                found.add(kw)
    return found

# --- 3. Normalizar listas de palavras-chave ---
problems  = [p.lower().strip() for p in problems]
concepts  = [c.lower().strip() for c in concepts]
contexts  = [c.lower().strip() for c in context]

# --- 4. Aplicar no DataFrame, unindo título e abstract SEM duplicar ---
work_ids_a_max_fs_3["problem_kw"] = work_ids_a_max_fs_3.apply(
    lambda row: list(
        extract_keywords(row["title"], problems, exact_match_words)
        | extract_keywords(row["abstract"], problems, exact_match_words)
    ),
    axis=1
)

work_ids_a_max_fs_3["concept_kw"] = work_ids_a_max_fs_3.apply(
    lambda row: list(
        extract_keywords(row["title"], concepts, exact_match_words)
        | extract_keywords(row["abstract"], concepts, exact_match_words)
    ),
    axis=1
)

work_ids_a_max_fs_3["context_kw"] = work_ids_a_max_fs_3.apply(
    lambda row: list(
        extract_keywords(row["title"], contexts, exact_match_words)
        | extract_keywords(row["abstract"], contexts, exact_match_words)
    ),
    axis=1
)

# --- 5. Identificar casos problemáticos ---
