TITLE        = "Tabela X – Palavras-chave mais frequentes"
SOURCE       = f"Fonte: Elaboração própria ({date.today().year})."
MAX_ROWS     = 30   # linhas por tabela/página
OUT_BASENAME = "tabela_keywords"  # base do nome dos arquivos

# ---------------- utilidades ----------------
def rename_columns(df: pd.DataFrame) -> pd.DataFrame:
    return df.rename(columns={
        "keyword": "Palavra-chave",
        "count": "Contagem",
        "percent": "Percentual (%)"
    })

def fmt_int_br(x):
    try:
        return f"{int(x):,}".replace(",", ".")
    except Exception:
        return x

def fmt_pct_br(x):
    try:
        return f"{float(x):.1f}%".replace(".", ",")
    except Exception:
        return x

def split_pages(df: pd.DataFrame, max_rows: int = MAX_ROWS):
    n_pages = math.ceil(len(df)/max_rows)
    for i in range(n_pages):
        yield i+1, df.iloc[i*max_rows:(i+1)*max_rows].copy()

# ---------------- estilo ABNT ----------------
def style_abnt(df_page: pd.DataFrame, subtitle: str = "") -> Styler:
    sty = (
        df_page.style
        .hide(axis="index")
        .set_table_styles([
            {'selector': 'table',
             'props': [('border-collapse','collapse'),
                       ('font-family','"Times New Roman", Times, serif'),
                       ('font-size','12pt'),
                       ('color','#000'),
                       ('width','100%'),
                       ('border-top','1pt solid #000'),
                       ('border-bottom','1pt solid #000')]},
            {'selector': 'thead th',
             'props': [('font-weight','bold'),
                       ('text-align','left'),
                       ('border-bottom','1pt solid #000'),
                       ('padding','4pt 6pt')]},
            {'selector': 'tbody td',
             'props': [('padding','3pt 6pt')]},
        ])
        .set_properties(subset=pd.IndexSlice[:, ["Palavra-chave"]], **{'text-align':'left'})
        .set_properties(subset=pd.IndexSlice[:, ["Contagem","Percentual (%)"]], **{'text-align':'right'})
        .format({"Contagem": fmt_int_br, "Percentual (%)": fmt_pct_br})
    )
    caption_html = f"<div style='font-family:Times New Roman;font-size:12pt;margin-bottom:6pt'><b>{TITLE}</b>"
    if subtitle:
        caption_html += f"<br><span style='font-size:10pt'>{subtitle}</span>"
    caption_html += "</div>"
    foot_html = f"<div style='font-family:Times New Roman;font-size:10pt;margin-top:4pt'>{SOURCE}</div>"
    return sty.set_caption(caption_html + foot_html)

# ---------------- exportação principal ----------------
def build_and_save_tables(keyword_df: pd.DataFrame, out_dir: str = "."):
    # ordenação padrão: contagem desc
    df = keyword_df.copy()
    df = df.sort_values("count", ascending=False, kind="stable")
