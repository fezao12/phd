import pandas as pd
import re

# --- 1. Exceções para match exato ---
exact_match_words = {"tin", "lead"}

# --- 2. Função de extração robusta (usa set para não duplicar) ---
def extract_keywords(text, keywords, exact_match_words):
    if pd.isna(text):
        return set()
    text = text.lower()
    found = set()
    for kw in keywords:
        kw_lc = kw.lower().strip()
        if kw_lc in exact_match_words:
            if re.search(rf'\b{re.escape(kw_lc)}\b', text):
                found.add(kw)
        else:
            if kw_lc in text:
                found.add(kw)
    return found

# --- 3. Normalizar listas de palavras-chave ---
problems  = [p.lower().strip() for p in problems]
concepts  = [c.lower().strip() for c in concepts]
contexts  = [c.lower().strip() for c in context]

